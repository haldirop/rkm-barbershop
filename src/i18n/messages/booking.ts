export const booking: Record<Locale, BookingMessages> = { nl, en, de };

/** Form errors (Dutch from the shared checks) in the visitor's language. */
export function localizeFieldErrors<T extends Partial<Record<string, string>>>(errors: T, locale: Locale): T {
  if (locale === "nl") return errors;
  const table = booking[locale].validation;
  return Object.fromEntries(Object.entries(errors).map(([field, message]) => [field, message ? (table[message] ?? message) : message])) as T;
}
